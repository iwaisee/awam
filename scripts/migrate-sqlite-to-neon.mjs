#!/usr/bin/env node
/* One-time migration: copy the legacy local SQLite stores (data/*.db) into
   the Neon Postgres project. Idempotent — rows that already exist remotely
   (matched on primary key) are skipped, so re-running never clobbers newer
   Neon data.

   Usage:
     node scripts/migrate-sqlite-to-neon.mjs [--truncate]

   DATABASE_URL is read from the environment, .env.local, or .env.
   --truncate empties the four Neon tables first (fresh start), otherwise
   existing rows are preserved and only missing rows are inserted. */

import { DatabaseSync } from "node:sqlite";
import { readFileSync, existsSync } from "node:fs";
import path from "node:path";
import pg from "pg";

const ROOT = path.resolve(import.meta.dirname, "..");
const DATA_DIR = path.join(ROOT, "data");
const TRUNCATE = process.argv.includes("--truncate");

/* ------------------------------ env + client ----------------------------- */

function loadDatabaseUrl() {
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL;
  for (const file of [".env.local", ".env"]) {
    const p = path.join(ROOT, file);
    if (!existsSync(p)) continue;
    const match = readFileSync(p, "utf8")
      .split("\n")
      .find((line) => /^\s*DATABASE_URL\s*=/.test(line));
    if (match) return match.split("=").slice(1).join("=").trim().replace(/^["']|["']$/g, "");
  }
  return null;
}

const DATABASE_URL = loadDatabaseUrl();
if (!DATABASE_URL) {
  console.error(
    "DATABASE_URL not found. Link the Neon project and run `neon env pull`, or export DATABASE_URL."
  );
  process.exit(1);
}

const isLocal = /(?:localhost|127\.0\.0\.1)/.test(DATABASE_URL);
const pool = new pg.Pool({
  connectionString: DATABASE_URL,
  // Neon endpoints require TLS; local Postgres does not.
  ...(isLocal ? {} : { ssl: { rejectUnauthorized: false } }),
});

/* ------------------------------- SQLite side ------------------------------ */

function openSqlite(file) {
  const p = path.join(DATA_DIR, file);
  if (!existsSync(p)) return null;
  return new DatabaseSync(p);
}

function readRows(db, table) {
  const columns = db.prepare(`PRAGMA table_info(${table})`).all().map((c) => c.name);
  if (columns.length === 0) return { columns, rows: [] };
  const rows = db.prepare(`SELECT * FROM ${table}`).all();
  return { columns, rows };
}

/* --------------------------------- helpers -------------------------------- */

const q = (text, params = []) => pool.query(text, params);

async function applySchema() {
  const schema = readFileSync(path.join(ROOT, "db", "schema.sql"), "utf8");
  await q(schema);
}

function columnList(columns) {
  return columns.join(", ");
}

function placeholders(columns) {
  // $1, $2 … with ::jsonb casts applied by the caller where needed.
  return columns.map((_, i) => `$${i + 1}`).join(", ");
}

async function migrateKeyValueJson({ label, sqliteFile, sqliteTable, pgTable }) {
  const db = openSqlite(sqliteFile);
  const { columns, rows } = db ? readRows(db, sqliteTable) : { columns: [], rows: [] };
  if (rows.length === 0) {
    console.log(`• ${label}: nothing to migrate`);
    return;
  }
  let inserted = 0;
  for (const row of rows) {
    const values = columns.map((c) => {
      const raw = row[c];
      // JSON columns arrive as JSON text — cast them server-side.
      if (["value", "data"].includes(c)) return raw === null ? null : String(raw);
      return raw;
    });
    const casts = columns
      .map((c, i) => (["value", "data"].includes(c) ? `$${i + 1}::jsonb` : `$${i + 1}`))
      .join(", ");
    const result = await q(
      `INSERT INTO ${pgTable} (${columnList(columns)}) VALUES (${casts})
       ON CONFLICT DO NOTHING`,
      values
    );
    inserted += result.rowCount ?? 0;
  }
  console.log(`• ${label}: ${rows.length} row(s) read, ${inserted} inserted`);
}

/* ---------------------------------- run ----------------------------------- */

async function main() {
  console.log(`Migrating local SQLite stores → ${isLocal ? "local Postgres" : "Neon"}`);
  await applySchema();
  console.log("✓ schema ensured");

  if (TRUNCATE) {
    await q("TRUNCATE app_state, registry, reports, citizen_admin");
    console.log("✓ Neon tables truncated (--truncate)");
  }

  // 1. app_state KV store (coverage, admin profile, prefs, waitlist, squad state).
  await migrateKeyValueJson({
    label: "app_state",
    sqliteFile: "appstate.db",
    sqliteTable: "app_state",
    pgTable: "app_state",
  });

  // 2. Departments registry (single JSON document).
  await migrateKeyValueJson({
    label: "registry",
    sqliteFile: "departments.db",
    sqliteTable: "registry",
    pgTable: "registry",
  });

  // 3. Reports ledger — the rowid column is regenerated by the identity
  //    column `seq`, so it is deliberately not copied. Legacy SQLite stores
  //    tags as a JSON array and coordinates as a JSON {lat,lng} object; the
  //    Neon table takes selected_tags TEXT[] and latitude/longitude columns.
  {
    const db = openSqlite("reports.db");
    if (!db) {
      console.log("• reports: nothing to migrate");
    } else {
      const { columns, rows } = readRows(db, "reports");
      const baseColumns = columns.filter(
        (c) => c !== "rowid" && c !== "seq" && c !== "coordinates",
      );
      const copyColumns = [...baseColumns, "latitude", "longitude"];
      const tagsIndex = copyColumns.indexOf("selected_tags");
      let inserted = 0;
      for (const row of rows) {
        const values = baseColumns.map((c) => {
          const raw = row[c];
          if (c === "selected_tags" && raw !== null && raw !== undefined) {
            try {
              const parsed = JSON.parse(String(raw));
              return Array.isArray(parsed) ? parsed : [];
            } catch {
              return [];
            }
          }
          return raw;
        });
        const coords =
          row.coordinates !== null && row.coordinates !== undefined
            ? JSON.parse(String(row.coordinates))
            : null;
        values.push(coords?.lat ?? null, coords?.lng ?? null);
        const placeholders = copyColumns.map((_, i) => `$${i + 1}`).join(", ");
        const result = await q(
          `INSERT INTO reports (${columnList(copyColumns)}) VALUES (${placeholders})
           ON CONFLICT (id) DO NOTHING`,
          values
        );
        inserted += result.rowCount ?? 0;
      }
      console.log(`• reports: ${rows.length} row(s) read, ${inserted} inserted`);
    }
  }

  // 4. Citizen admin governance state (0/1 integers → booleans).
  {
    const db = openSqlite("reports.db");
    if (!db) {
      console.log("• citizen_admin: nothing to migrate");
    } else {
      const { rows } = readRows(db, "citizen_admin");
      let inserted = 0;
      for (const row of rows) {
        const result = await q(
          `INSERT INTO citizen_admin (key, badge_override, score_modifier, standing, blacklisted, updated_at)
           VALUES ($1, $2, $3, $4, $5, $6)
           ON CONFLICT (key) DO NOTHING`,
          [
            row.key,
            Number(row.badge_override ?? 0) === 1,
            Number(row.score_modifier ?? 0),
            String(row.standing ?? "active"),
            Number(row.blacklisted ?? 0) === 1,
            String(row.updated_at ?? new Date().toISOString()),
          ]
        );
        inserted += result.rowCount ?? 0;
      }
      console.log(`• citizen_admin: ${rows.length} row(s) read, ${inserted} inserted`);
    }
  }

  // Verification pass — row counts straight from Neon.
  const { rows: counts } = await q(
    `SELECT 'app_state' AS t, count(*)::int AS n FROM app_state
     UNION ALL SELECT 'registry', count(*)::int FROM registry
     UNION ALL SELECT 'reports', count(*)::int FROM reports
     UNION ALL SELECT 'citizen_admin', count(*)::int FROM citizen_admin`
  );
  console.log("\nNeon row counts:");
  for (const { t, n } of counts) console.log(`  ${t}: ${n}`);
}

main()
  .then(() => pool.end())
  .catch((error) => {
    console.error("Migration failed:", error);
    pool.end().finally(() => process.exit(1));
  });
